import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
const { chromium } = createRequire(import.meta.url)(process.env.IKARUS_PLAYWRIGHT_MODULE ?? 'playwright')
const output = process.env.IKARUS_QA_OUTPUT ?? 'benchmark-results/browser'
fs.mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
page.on('dialog', (dialog) => dialog.accept())
let blockSubmission = true
await page.route('**/api/rankings/submit', (route) => blockSubmission ? route.abort() : route.continue())
try {
  await page.goto(process.env.IKARUS_QA_URL ?? 'http://127.0.0.1:5173/')
  await page.getByLabel('Email', { exact: true }).fill('qa-part-f@example.test')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.getByText(/Pressione.*Enter/).waitFor()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Survivor', exact: true }).click()
  await page.getByRole('button', { name: 'Jogar', exact: true }).click()
  await page.getByText(/SPRINT 1 · WAVE 0/).waitFor({ timeout: 20000 })
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('tab', { name: 'Laboratório' }).count(), 0)
  assert.match(await page.locator('#hud-root').innerText(), /NOVA BOMB x0/)
  await page.getByRole('button', { name: 'Abandonar partida' }).click()
  await page.getByRole('button', { name: 'Normal', exact: true }).click()
  await page.getByRole('button', { name: 'Jogar', exact: true }).click()
  await page.getByText(/SPRINT 1 · WAVE 0/).waitFor({ timeout: 20000 })
  await page.keyboard.press('Escape')
  await page.getByRole('tab', { name: 'Laboratório', exact: true }).click()
  await page.locator('.lab-recipes article').filter({ hasText: 'Construir Plasma' }).getByRole('button', { name: 'Construir', exact: true }).click()
  await page.getByText('Materiais ou energia insuficientes.').waitFor()
  await page.screenshot({ path: path.join(output, 'part-f-lab.png') })
  await page.getByRole('tab', { name: 'Audio', exact: true }).click()
  assert.equal(await page.getByRole('slider').count(), 2)
  await page.getByRole('tab', { name: 'Dev', exact: true }).click()
  await page.getByRole('button', { name: 'Testar fim de partida', exact: true }).click()
  await page.getByRole('button', { name: 'Tentar registrar novamente', exact: true }).waitFor({ timeout: 20000 })
  await page.reload()
  await page.getByText(/Resultado recuperado deste navegador/).waitFor({ timeout: 20000 })
  await page.screenshot({ path: path.join(output, 'part-f-recovery.png') })
  blockSubmission = false
  await page.getByRole('button', { name: 'Tentar registrar novamente', exact: true }).click()
  await page.getByText('Resultado de teste registrado fora dos recordes.').waitFor({ timeout: 20000 })
  await page.getByRole('button', { name: 'Recordes', exact: true }).click()
  await page.getByRole('tab', { name: 'Survivor', exact: true }).click()
  await page.getByText('Nenhum recorde neste período. Sua próxima partida pode ser a primeira.').waitFor()
  await page.getByRole('button', { name: 'Voltar', exact: true }).click()
  await page.getByRole('button', { name: 'Voltar ao menu', exact: true }).click()
  await page.getByRole('button', { name: 'Normal', exact: true }).click()
  await page.getByRole('button', { name: 'Jogar', exact: true }).click()
  await page.getByText(/SPRINT 1 · WAVE 0/).waitFor({ timeout: 20000 })
  await page.keyboard.down('f'); await page.waitForTimeout(6000); await page.keyboard.up('f')
  await page.screenshot({ path: path.join(output, 'part-f-gameplay.png') })
  assert.deepEqual(errors, [])
  fs.writeFileSync(path.join(output, 'smoke-result.json'), JSON.stringify({ passed: true, flows: ['Survivor laser-only/no Lab', 'Normal Lab/insufficient materials', 'audio controls', 'failed submit', 'reload recovery', 'retry', 'mode boards', 'Title/new run', 'keyboard fire'], pageErrors: errors }, null, 2))
  console.log('Browser smoke passed.')
} finally { await browser.close() }
